function distanciaMetros(a: [number, number], b: [number, number]): number {
  const r = 6371000;
  const rad = Math.PI / 180;
  const dLat = (b[0] - a[0]) * rad;
  const dLng = (b[1] - a[1]) * rad;
  const lat1 = a[0] * rad;
  const lat2 = b[0] * rad;
  const h =
    Math.sin(dLat / 2) * Math.sin(dLat / 2) +
    Math.cos(lat1) * Math.cos(lat2) * Math.sin(dLng / 2) * Math.sin(dLng / 2);
  return 2 * r * Math.atan2(Math.sqrt(h), Math.sqrt(1 - h));
}

function muestrearTramoLineal(
  puntos: [number, number][],
  pasoMetros: number,
  incluirUltimo: boolean,
): [number, number][] {
  if (puntos.length === 0) return [];
  if (puntos.length === 1) return [puntos[0]];

  const acum: number[] = [0];
  let total = 0;
  for (let i = 1; i < puntos.length; i++) {
    total += distanciaMetros(puntos[i - 1], puntos[i]);
    acum.push(total);
  }

  const cantidadPasos = Math.max(1, Math.round(total / pasoMetros));
  const salida: [number, number][] = [];
  const limite = incluirUltimo ? cantidadPasos : cantidadPasos - 1;

  for (let s = 0; s <= limite; s++) {
    const d = (s / cantidadPasos) * total;
    let idx = 0;
    while (idx < acum.length - 2 && acum[idx + 1] < d) {
      idx++;
    }
    const d0 = acum[idx];
    const d1 = acum[idx + 1];
    const seg = Math.max(0.0001, d1 - d0);
    const t = Math.min(1, Math.max(0, (d - d0) / seg));
    const p0 = puntos[idx];
    const p1 = puntos[idx + 1];
    salida.push([
      Number((p0[0] + (p1[0] - p0[0]) * t).toFixed(6)),
      Number((p0[1] + (p1[1] - p0[1]) * t).toFixed(6)),
    ]);
  }

  return salida;
}

function construirRutaLineal(ruta: RutaUrbana, pasoMetros = 10): RutaUrbana {
  const coords = ruta.coordenadas;
  const paraderosOrdenados = [...ruta.paraderos].sort((a, b) => a.index - b.index);
  const nuevasCoords: [number, number][] = [];
  const nuevosParaderos: ParaderoRuta[] = [];

  for (let i = 0; i < paraderosOrdenados.length; i++) {
    const pActual = paraderosOrdenados[i];
    const pSiguiente = paraderosOrdenados[i + 1];
    const inicio = pActual.index;
    const fin = pSiguiente ? pSiguiente.index : coords.length - 1;
    const subPuntos = coords.slice(inicio, fin + 1);
    const indiceParadero = nuevasCoords.length;
    const muestreados = muestrearTramoLineal(subPuntos, pasoMetros, false);

    nuevasCoords.push(...muestreados);
    const puntoParadero = nuevasCoords[indiceParadero] ?? coords[inicio];
    nuevosParaderos.push({
      id: pActual.id,
      nombre: pActual.nombre,
      lat: puntoParadero[0],
      lng: puntoParadero[1],
      index: indiceParadero,
    });
  }

  return {
    id: ruta.id,
    nombre: ruta.nombre,
    color: ruta.color,
    paraderos: nuevosParaderos,
    coordenadas: nuevasCoords,
  };
}

